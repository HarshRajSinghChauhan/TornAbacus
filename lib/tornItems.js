/**
 * Identify destination country from flight duration in seconds
 * Handles both Private Airstrip (PI) flight times and Standard Commercial flight times.
 */
export function getCountryFromDuration(durationSeconds, isPersonal = true) {
  const duration = Number(durationSeconds);
  if (!duration || duration <= 0) return null;

  // Private Airstrip times (with built-in ±3% game variance)
  // Mexico: ~14m (~840s)
  // Canada: ~26m (~1560s)
  // Cayman Islands: ~40m (~2400s)
  // Hawaii: ~1h 25m (~5100s)
  // United Kingdom: ~1h 47m (6420s - 6540s)
  // Switzerland: ~1h 58m (~7080s)
  // Argentina: ~2h 13m (~7980s)
  // Japan: ~2h 22m (~8520s)
  // China: ~2h 33m (~9180s)
  // UAE: ~3h 01m (~10860s)
  // South Africa: ~3h 37m (~13020s)
  if (isPersonal) {
    if (duration >= 700 && duration <= 1100) return "Mexico";
    if (duration >= 1400 && duration <= 1800) return "Canada";
    if (duration >= 2100 && duration <= 2800) return "Cayman Islands";
    if (duration >= 4700 && duration <= 5500) return "Hawaii";
    if (duration >= 6000 && duration <= 6750) return "United Kingdom";
    if (duration >= 6850 && duration <= 7450) return "Switzerland";
    if (duration >= 7600 && duration <= 8250) return "Argentina";
    if (duration >= 8300 && duration <= 8800) return "Japan";
    if (duration >= 8900 && duration <= 9600) return "China";
    if (duration >= 10400 && duration <= 11500) return "UAE";
    if (duration >= 12500 && duration <= 14500) return "South Africa";
  }

  // Standard Commercial Flights (without Private Airstrip)
  // Mexico: ~1200s (20m)
  // Canada: ~2220s (37m)
  // Cayman Islands: ~3420s (57m)
  // Hawaii: ~7260s (121m)
  // United Kingdom: ~9120s (152m)
  // Switzerland: ~10140s (169m)
  // Argentina: ~11340s (189m)
  // Japan: ~12180s (203m)
  // China: ~13140s (219m)
  // UAE: ~15540s (259m)
  // South Africa: ~18660s (311m)
  if (duration >= 1100 && duration <= 1350) return "Mexico";
  if (duration >= 2000 && duration <= 2500 && !isPersonal) return "Canada";
  if (duration >= 3200 && duration <= 3700) return "Cayman Islands";
  if (duration >= 7000 && duration <= 7600 && !isPersonal) return "Hawaii";
  if (duration >= 8800 && duration <= 9500) return "United Kingdom";
  if (duration >= 9800 && duration <= 10600) return "Switzerland";
  if (duration >= 11000 && duration <= 11800) return "Argentina";
  if (duration >= 11900 && duration <= 12500) return "Japan";
  if (duration >= 12800 && duration <= 13600) return "China";
  if (duration >= 15000 && duration <= 16500) return "UAE";
  if (duration >= 18000 && duration <= 19500) return "South Africa";

  return null;
}

/**
 * Resolve flight destination and foreign country from flight log data
 */
export function resolveFlightDestination(data, title = "") {
  if (!data) return { destination: "Overseas", country: "Overseas", isHome: false };

  const isPersonal =
    data.travel_method === "personal" ||
    (title && (title.toLowerCase().includes("private") || title.toLowerCase().includes("airstrip")));

  const duration = Number(data.duration) || 0;
  const durationCountry = getCountryFromDuration(duration, isPersonal);

  // Check 3-letter code or string in destination/country
  const rawDest = String(data.destination || "").toLowerCase().trim();
  const rawCountry = String(data.country || "").toLowerCase().trim();
  const codeCountry = TORN_DESTINATION_CODES[rawDest] || TORN_DESTINATION_CODES[rawCountry];

  const destId = Number(data.destination);
  const originId = Number(data.origin);

  // If destination is 1, the user is flying HOME to Torn City
  if (destId === 1) {
    const foreignCountry = durationCountry || codeCountry || (originId ? getCountryByAreaId(originId) : null) || "Overseas";
    return {
      destination: "Torn City",
      country: foreignCountry,
      isHome: true,
      foreignCountry,
    };
  }

  // Outbound flight abroad
  const foreignCountry = durationCountry || codeCountry || (destId ? getCountryByAreaId(destId) : null) || "Overseas";
  return {
    destination: foreignCountry,
    country: foreignCountry,
    isHome: false,
    foreignCountry,
  };
}
